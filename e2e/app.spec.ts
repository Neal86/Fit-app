import { expect, test } from '@playwright/test'

test('onboarding, durable set logging, plan editing, backup and offline reload', async ({ page, context }, testInfo) => {
  const exceptions: string[] = []
  page.on('pageerror', error => exceptions.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await page.getByLabel('First name').fill('Jordan')
  await page.getByLabel('Weight (kg)', { exact: true }).fill('65')
  await page.getByRole('button', { name: 'Start training' }).click()
  await expect(page.getByRole('heading', { name: 'Ready, Jordan?' })).toBeVisible()
  await page.getByRole('link', { name: 'Start workout', exact: true }).click()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  await page.getByLabel('Bench Press set 1 reps', { exact: true }).fill('8')
  await page.getByLabel('Bench Press set 1 weight', { exact: true }).fill('20')
  await page.getByRole('button', { name: 'Complete Bench Press set 1', exact: true }).click()
  await expect(page.getByText('Rest:', { exact: false })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Bench Press set 1 weight', { exact: true })).toHaveValue('20')
  await expect(page.getByRole('button', { name: 'Undo Bench Press set 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause timer', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('training-session.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Finish and save workout', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your progress' })).toBeVisible()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('fit-app-state-v2')!))
  expect(saved.logs).toHaveLength(1)
  expect(saved.logs[0].durationSeconds).toBeLessThan(60)
  expect(saved.logs[0].sets[0].reps).toBe(8)
  expect(saved.weightHistory[0].weightKg).toBe(65)
  await page.goto('/plan')
  await page.getByLabel('Workout title').fill('My strength session')
  await page.getByRole('button', { name: /Save workout plan/ }).click()
  await expect(page.getByRole('status')).toHaveText('Workout plan saved')
  await page.goto('/profile')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export backup', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^fitflow-backup-.*\.json$/)
  await page.locator('input[type=file]').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":3}') })
  await expect(page.getByRole('alert')).toContainText('invalid')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('fit-app-state-v2')!).logs.length)).toBe(1)
  await page.screenshot({ path: testInfo.outputPath('profile-backup.png'), fullPage: true })
  await page.evaluate(() => navigator.serviceWorker.ready)
  await context.setOffline(true)
  await page.goto('/workouts')
  await expect(page.getByRole('heading', { name: 'Your workouts' })).toBeVisible()
  await expect(page.getByRole('link', { name: /My strength session/ })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Your workouts' })).toBeVisible()
  expect(exceptions).toEqual([])
})

test('corrupt storage is preserved and recoverable without an automatic wipe', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('fit-app-state-v2', '{broken'))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Your saved data needs attention' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('fit-app-state-v2'))).toBe('{broken')
  await expect(page.getByRole('button', { name: 'Download original saved data' })).toBeVisible()
})

test('nutrition drafts, reviewed schedule changes and unconfigured account privacy', async ({ page }) => {
  const cloudRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/v1/')) cloudRequests.push(request.url()) })
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await page.getByRole('button', { name: 'Start training' }).click()
  await page.goto('/nutrition')
  await page.getByRole('button', { name: 'Add food', exact: true }).click()
  await page.getByLabel('Food name', { exact: true }).fill('Synthetic unfinished entry')
  await page.goto('/')
  await page.goto('/nutrition')
  await expect(page.getByLabel('Food name', { exact: true })).toHaveValue('Synthetic unfinished entry')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Add water', exact: true }).click()
  await page.getByLabel('Water amount (ml)', { exact: true }).fill('250')
  await page.getByRole('button', { name: 'Save water entry', exact: true }).click()
  await page.reload()
  await expect(page.getByTestId('nutrition-total-water')).toContainText('250')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/schedule')
  await page.getByLabel('Monday', { exact: true }).check()
  await page.getByRole('button', { name: 'Preview weekly schedule', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review your schedule' })).toBeVisible()
  await page.getByRole('button', { name: 'Apply this schedule', exact: true }).click()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('fit-app-state-v2')!))
  expect(saved.workouts).toHaveLength(1)
  expect(saved.planHistory).toHaveLength(1)
  expect(saved.nutrition.hydration).toHaveLength(1)
  await page.getByText('Previous plan versions (1)', { exact: true }).click()
  await page.getByRole('button', { name: 'Restore version', exact: true }).click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('fit-app-state-v2')!).workouts.length)).toBe(4)
  await page.goto('/account')
  await expect(page.getByRole('heading', { name: 'Local data stays with you' })).toBeVisible()
  expect(cloudRequests).toEqual([])
})
