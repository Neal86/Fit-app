const date = '2026-10-15'
const food: MealEntry = { id: 'food-1', date, mealType: 'Lunch', foodName: 'My lunch', serving: '1 bowl', calories: 320, protein: 12, carbs: 40, fat: 10 }
const water: HydrationEntry = { id: 'water-1', date, milliliters: 250, note: 'With lunch' }
const withEntries = (): NutritionState => ({ ...createNutritionState(), meals: [{ ...food }], hydration: [{ ...water }] })
function Harness({ initial = createNutritionState(), persist = () => true }: { initial?: NutritionState; persist?: (next: NutritionState) => boolean }) {
  const [state, setState] = useState(initial)
  const latest = useRef(state)
  const onUpdate: NutritionUpdate = change => {
    try {
      const next = change(latest.current)
      if (!persist(next)) return false
      latest.current = next; setState(next); return true
    } catch { return false }
  }
  return <Nutrition state={state} onUpdate={onUpdate} />
}
const change = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } })
const fillMeal = () => {
  change('Food name', 'My entered food'); change('Amount / serving note', '150 g')
  change('Calories (kcal)', '200.5'); change('Protein (g)', '10.2'); change('Carbohydrates (g)', '25'); change('Fat (g)', '5')
}
