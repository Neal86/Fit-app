import type { CloudSession } from './cloud'

/** Source-only protocol. Nothing in this module discovers, registers or calls a plugin. */
export const NATIVE_ACCOUNT_VERSION = 1 as const
export const NATIVE_ACCOUNT_LIMITS = Object.freeze({
  requestBytes: 8 * 1024,
  snapshotBytes: 10 * 1024 * 1024 + 1024,
  responseBytes: 10 * 1024 * 1024 + 64 * 1024,
  challengeResponseBytes: 256 * 1024,
  exportResponseBytes: 64 * 1024 * 1024,
  errorBytes: 1024,
  depth: 32,
  nodes: 1_000_000,
  requestTimeoutMs: 20_000,
  absoluteSessionMs: 8 * 60 * 60 * 1000,
  idleSessionMs: 30 * 60 * 1000,
})
export type NativeAccountJson = null | boolean | number | string | readonly NativeAccountJson[] | { readonly [key: string]: NativeAccountJson }
export type NativeAccountMethod = 'GET' | 'POST' | 'PUT' | 'DELETE'
export type NativeAccountCapabilitiesQuery = Readonly<{ version: 1 }>
export type NativeAccountCapabilities = Readonly<{ version: 1; available: boolean }>
export type NativeAccountContext = Readonly<{ version: 1; contextId: string }>
export type NativeAccountRequest = Readonly<{
  version: 1; contextId: string; requestId: string; method: NativeAccountMethod; path: string; body?: NativeAccountJson
}>
export type NativeAccountReply = Readonly<{
  version: 1; contextId: string; requestId: string; status: number; body?: NativeAccountJson
}>
export type NativeAccountSession = Readonly<Omit<CloudSession, 'user'> & { user: Readonly<CloudSession['user']> }>

/** Declaration only. Capabilities and context operations MUST remain local-only, with no network. */
export interface NativeAccountPort {
  capabilities(query: NativeAccountCapabilitiesQuery): Promise<NativeAccountCapabilities>
  startContext(context: NativeAccountContext): Promise<NativeAccountContext>
  clearContext(context: NativeAccountContext): Promise<NativeAccountContext>
  request(command: NativeAccountRequest): Promise<NativeAccountReply>
}

export class NativeAccountContractError extends Error {
  readonly code = 'invalid_native_account_contract'
  constructor() { super('Native account protocol data was rejected.'); this.name = 'NativeAccountContractError' }
}
const invalid = (): never => { throw new NativeAccountContractError() }
// Contexts and requests use fresh random UUIDs. No identifiers are generated by this module.
const uuid = (value: unknown): value is string => typeof value === 'string' && value.length === 36 && /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(value)
const object = (value: NativeAccountJson): value is { readonly [key: string]: NativeAccountJson } => value !== null && typeof value === 'object' && !Array.isArray(value)
const encoder = new TextEncoder()

/** Copy JSON data without invoking getters/toJSON, accepting lossy coercion, or retaining references. */
function copyJson(value: unknown, byteLimit: number): NativeAccountJson {
  let bytes = 0; let nodes = 0
  const active = new WeakSet<object>()
  const charge = (amount: number) => { bytes += amount; if (bytes > byteLimit) invalid() }
  const stringBytes = (text: string) => {
    if (text.length > byteLimit - bytes) invalid()
    charge(encoder.encode(JSON.stringify(text)).byteLength)
  }
  const visit = (input: unknown, depth: number): NativeAccountJson => {
    if (++nodes > NATIVE_ACCOUNT_LIMITS.nodes || depth > NATIVE_ACCOUNT_LIMITS.depth) invalid()
    if (input === null) { charge(4); return null }
    if (typeof input === 'boolean') { charge(input ? 4 : 5); return input }
    if (typeof input === 'string') { stringBytes(input); return input }
    if (typeof input === 'number') {
      if (!Number.isFinite(input) || Object.is(input, -0)) invalid()
      charge(String(input).length); return input
    }
    if (typeof input !== 'object' || !input || active.has(input)) return invalid()
    const array = Array.isArray(input)
    const prototype = Object.getPrototypeOf(input)
    if (array ? prototype !== Array.prototype : prototype !== Object.prototype && prototype !== null) invalid()
    active.add(input)
    const descriptors = Object.getOwnPropertyDescriptors(input)
    const keys = Reflect.ownKeys(descriptors)
    charge(2)
    if (array) {
      const length = descriptors.length?.value
      if (!Number.isSafeInteger(length) || length < 0 || length > NATIVE_ACCOUNT_LIMITS.nodes || keys.length !== length + 1) invalid()
      const result: NativeAccountJson[] = []
      for (let index = 0; index < length; index++) {
        const entry = descriptors[String(index)]
        if (!entry || !('value' in entry) || !entry.enumerable) invalid()
        if (index) charge(1)
        result.push(visit(entry.value, depth + 1))
      }
      active.delete(input)
      return Object.freeze(result)
    }
    const result: Record<string, NativeAccountJson> = {}
    keys.forEach((key, index) => {
      if (typeof key !== 'string') return invalid()
      const entry = descriptors[key]
      if (!('value' in entry) || !entry.enumerable) invalid()
      if (index) charge(1)
      stringBytes(key); charge(1)
      // defineProperty keeps a JSON key named __proto__ as data, never a prototype mutation.
      Object.defineProperty(result, key, { value: visit(entry.value, depth + 1), enumerable: true })
    })
    active.delete(input)
    return Object.freeze(result)
  }
  try { return visit(value, 0) } catch { return invalid() }
}
function fields(value: NativeAccountJson, required: readonly string[], optional: readonly string[] = []): asserts value is { readonly [key: string]: NativeAccountJson } {
  if (!object(value) || required.some(key => !Object.hasOwn(value, key)) || Object.keys(value).some(key => !required.includes(key) && !optional.includes(key))) invalid()
}

/** Both arguments must come from trusted native packaging, NEVER a WebView command or page origin. */
export function nativeAccountEndpoint(packagedConfig: unknown, expectedEndpoint: unknown): string | null {
  if (typeof packagedConfig !== 'string' || typeof expectedEndpoint !== 'string' || packagedConfig !== expectedEndpoint || packagedConfig.length > 2048) return null
  if (!packagedConfig.startsWith('https://') || /[\\%\s?#]/.test(packagedConfig)) return null
  try {
    const url = new URL(packagedConfig)
    if (url.protocol !== 'https:' || !url.hostname || url.username || url.password || url.pathname !== '/api/native/v1' || url.search || url.hash || url.href !== packagedConfig) return null
    return packagedConfig
  } catch { return null }
}

export function readNativeAccountCapabilitiesQuery(value: unknown): NativeAccountCapabilitiesQuery {
  const copy = copyJson(value, 64)
  fields(copy, ['version'])
  if (copy.version !== NATIVE_ACCOUNT_VERSION) invalid()
  return copy as NativeAccountCapabilitiesQuery
}
export function readNativeAccountCapabilities(value: unknown): NativeAccountCapabilities {
  const copy = copyJson(value, 128)
  fields(copy, ['version', 'available'])
  if (copy.version !== NATIVE_ACCOUNT_VERSION || typeof copy.available !== 'boolean') invalid()
  return copy as NativeAccountCapabilities
}
export function readNativeAccountContext(value: unknown): NativeAccountContext {
  const copy = copyJson(value, 128)
  fields(copy, ['version', 'contextId'])
  if (copy.version !== NATIVE_ACCOUNT_VERSION || !uuid(copy.contextId)) invalid()
  return copy as NativeAccountContext
}

export function readNativeAccountContextReply(value: unknown, context: NativeAccountContext): NativeAccountContext {
  const command = readNativeAccountContext(context)
  const reply = readNativeAccountContext(value)
  if (reply.contextId !== command.contextId) invalid()
  return reply
}

